;WITH RequiredTech AS(
    SELECT DISTINCT ExpectedTechnology FROM #ExpectedTechnology
),
CatalogMatches AS(
    SELECT r.ExpectedTechnology,
           COUNT(ct.Id) AS ActiveCatalogMatches
    FROM RequiredTech r
    LEFT JOIN bbva.CatalogTechnology ct
      ON UPPER(LTRIM(RTRIM(ct.Name)))=UPPER(LTRIM(RTRIM(r.ExpectedTechnology)))
     AND ct.Status=N'ACTIVE'
    GROUP BY r.ExpectedTechnology
)
SELECT ExpectedTechnology,ActiveCatalogMatches
FROM CatalogMatches
WHERE ActiveCatalogMatches<>1
ORDER BY ExpectedTechnology;

