SELECT
    p.SofttekCode,
    e.FullName,
    p.CurrentTechnology AS TecnologiaActualAntes,
    e.ExpectedTechnology AS TecnologiaCorrecta,
    ctCurrent.Name AS CatalogoActual,
    ctExpected.Name AS CatalogoCorrecto
FROM #ExpectedTechnology e
JOIN bbva.Person p ON UPPER(LTRIM(RTRIM(p.SofttekCode)))=e.SofttekCode
LEFT JOIN bbva.CatalogTechnology ctCurrent ON ctCurrent.Id=p.CurrentTechnologyCatalogId
JOIN bbva.CatalogTechnology ctExpected
  ON UPPER(LTRIM(RTRIM(ctExpected.Name)))=UPPER(LTRIM(RTRIM(e.ExpectedTechnology)))
 AND ctExpected.Status=N'ACTIVE'
WHERE UPPER(LTRIM(RTRIM(ISNULL(p.CurrentTechnology,N''))))<>UPPER(LTRIM(RTRIM(e.ExpectedTechnology)))
   OR p.CurrentTechnologyCatalogId<>ctExpected.Id
ORDER BY e.FullName;

DECLARE @BeforeMismatch INT = (
    SELECT COUNT(*)
    FROM #ExpectedTechnology e
    JOIN bbva.Person p ON UPPER(LTRIM(RTRIM(p.SofttekCode)))=e.SofttekCode
    JOIN bbva.CatalogTechnology ctExpected
      ON UPPER(LTRIM(RTRIM(ctExpected.Name)))=UPPER(LTRIM(RTRIM(e.ExpectedTechnology)))
     AND ctExpected.Status=N'ACTIVE'
    WHERE UPPER(LTRIM(RTRIM(ISNULL(p.CurrentTechnology,N''))))<>UPPER(LTRIM(RTRIM(e.ExpectedTechnology)))
       OR p.CurrentTechnologyCatalogId<>ctExpected.Id
);

SELECT @BeforeMismatch AS RowsToRepair;

BEGIN TRY
    BEGIN TRANSACTION;

    DECLARE @Changed TABLE(
        PersonId UNIQUEIDENTIFIER PRIMARY KEY,
        OldTechnology NVARCHAR(240) NULL,
        NewTechnology NVARCHAR(240) NOT NULL
    );

    UPDATE p
       SET CurrentTechnology=ct.Name,
           CurrentTechnologyCatalogId=ct.Id,
           UpdatedAt=SYSUTCDATETIME(),
           UpdatedByEmail=N'data-repair@basebfs.local'
    OUTPUT inserted.Id,deleted.CurrentTechnology,inserted.CurrentTechnology
      INTO @Changed(PersonId,OldTechnology,NewTechnology)
    FROM bbva.Person p
    JOIN #ExpectedTechnology e
      ON UPPER(LTRIM(RTRIM(p.SofttekCode)))=e.SofttekCode
    JOIN bbva.CatalogTechnology ct
      ON UPPER(LTRIM(RTRIM(ct.Name)))=UPPER(LTRIM(RTRIM(e.ExpectedTechnology)))
     AND ct.Status=N'ACTIVE'
    WHERE UPPER(LTRIM(RTRIM(ISNULL(p.CurrentTechnology,N''))))<>UPPER(LTRIM(RTRIM(e.ExpectedTechnology)))
       OR p.CurrentTechnologyCatalogId<>ct.Id;

    DECLARE @Updated INT=@@ROWCOUNT;

    MERGE bbva.PersonFieldProvenance AS target
    USING(
        SELECT p.Id AS PersonId,N'CurrentTechnology' AS FieldName,N'TABLERO' AS SourceType,
               e.ExpectedTechnology AS SourceValue
        FROM #ExpectedTechnology e
        JOIN bbva.Person p ON UPPER(LTRIM(RTRIM(p.SofttekCode)))=e.SofttekCode
    ) AS source
    ON target.PersonId=source.PersonId
       AND target.FieldName=source.FieldName
       AND target.SourceType=source.SourceType
    WHEN MATCHED THEN
      UPDATE SET SourceValue=source.SourceValue,
                 LastSeenAt=SYSUTCDATETIME(),
                 UpdatedByEmail=N'data-repair@basebfs.local'
    WHEN NOT MATCHED THEN
      INSERT(PersonId,FieldName,SourceType,SourceValue,CreatedByEmail,UpdatedByEmail)
      VALUES(source.PersonId,source.FieldName,source.SourceType,source.SourceValue,N'data-repair@basebfs.local',N'data-repair@basebfs.local');

    INSERT INTO bbva.CollaboratorHistory(CollaboratorId,EventType,Description,CreatedByEmail)
    SELECT c.Id,
           N'DATA_REPAIR_CURRENT_TECHNOLOGY_V13',
           CONCAT(N'Tecnología actual corregida según TABLERO.TECNOLOGÍA EN LA QUE SE CERTIFICA: ',
                  ISNULL(ch.OldTechnology,N'(vacío)'),N' -> ',ch.NewTechnology,N'.'),
           N'data-repair@basebfs.local'
    FROM @Changed ch
    JOIN bbva.Collaborator c ON c.PersonId=ch.PersonId;

    DECLARE @Remaining INT = (
        SELECT COUNT(*)
        FROM #ExpectedTechnology e
        JOIN bbva.Person p ON UPPER(LTRIM(RTRIM(p.SofttekCode)))=e.SofttekCode
        JOIN bbva.CatalogTechnology ctExpected
          ON UPPER(LTRIM(RTRIM(ctExpected.Name)))=UPPER(LTRIM(RTRIM(e.ExpectedTechnology)))
         AND ctExpected.Status=N'ACTIVE'
        WHERE UPPER(LTRIM(RTRIM(ISNULL(p.CurrentTechnology,N''))))<>UPPER(LTRIM(RTRIM(e.ExpectedTechnology)))
           OR p.CurrentTechnologyCatalogId<>ctExpected.Id
    );

    IF @Remaining<>0
        THROW 51304, 'El postcheck encontró tecnologías aún desalineadas. Se revierte la transacción.', 1;

    COMMIT;

    PRINT '';
    PRINT '=== REPARACION V13 APLICADA ===';
    SELECT @BeforeMismatch AS DifferencesBefore,@Updated AS RowsUpdated,@Remaining AS DifferencesAfter;

    PRINT '';
    PRINT '=== POSTCHECK 183 PERSONAS ===';
    SELECT
        COUNT(*) AS SourcePeople,
        SUM(CASE WHEN UPPER(LTRIM(RTRIM(p.CurrentTechnology)))=UPPER(LTRIM(RTRIM(e.ExpectedTechnology))) THEN 1 ELSE 0 END) AS TextMatches,
        SUM(CASE WHEN p.CurrentTechnologyCatalogId=ct.Id THEN 1 ELSE 0 END) AS CatalogMatches
    FROM #ExpectedTechnology e
    JOIN bbva.Person p ON UPPER(LTRIM(RTRIM(p.SofttekCode)))=e.SofttekCode
    JOIN bbva.CatalogTechnology ct
      ON UPPER(LTRIM(RTRIM(ct.Name)))=UPPER(LTRIM(RTRIM(e.ExpectedTechnology)))
     AND ct.Status=N'ACTIVE';

